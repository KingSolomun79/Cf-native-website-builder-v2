// The five frozen REFERENCE_BOUND benchmark cases (issue #17, PRD sections
// 43-45, FINAL-DECISION-RECORD 130-131).
//
// FREEZE MEANS FREEZE: these definitions are the canonical benchmark ruler.
// A Reference Screenshot, replacement Business brief or expected identity is
// NEVER replaced silently — not because a case fails, not to reach the proof
// gate, not for convenience. A legitimate future change versions the case
// explicitly (definitionVersion bump), preserves the prior definition in
// history, and records an operator decision in FINAL-DECISION-RECORD.
//
// The five archetypes are exactly PRD 43's set — materially different DESIGN
// TOPOLOGY, not color/content variants:
//   1. asymmetric/editorial
//   2. image-heavy hospitality/travel
//   3. restrained corporate/professional
//   4. bold trades/local service
//   5. difficult but supported responsive/motion Reference
//
// Reference Screenshots are deterministic in-repo design compositions
// (benchmarks/<caseId>/reference-screenshot.png, bytes embedded in
// generated-frozen-screenshots.ts) with sha256-pinned identities. All five
// cases are SCREENSHOT_ONLY: the frozen target has no live URL that could
// drift, refresh, or vanish — PRD 43's URL recheck is vacuously satisfied.
//
// Replacement Businesses are standardized synthetic briefs: they carry no
// real contact data (example-only emails), so benchmark artifacts never leak
// Business/contact information.

