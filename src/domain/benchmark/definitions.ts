function hours(open: string, close: string, saturday: [string, string] | null): BusinessHours {
  return {
    monday: { status: "OPEN", open, close },
    tuesday: { status: "OPEN", open, close },
    wednesday: { status: "OPEN", open, close },
    thursday: { status: "OPEN", open, close },
    friday: { status: "OPEN", open, close },
    saturday: saturday ? { status: "OPEN", open: saturday[0], close: saturday[1] } : { status: "CLOSED" },
    sunday: { status: "CLOSED" },
  };
}

function services(items: Array<[string, string]>): ServiceItem[] {
  return items.map(([name, description]) => ({ name, description }));
}

