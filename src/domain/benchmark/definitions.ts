// Structural guarantee: EXACTLY five unique cases, one per slot, matching the
// PRD 43 archetype set — the frozen set is the set.
export function assertBenchmarkShape(): void {
  if (BENCHMARK_CASE_DEFINITIONS.length !== 5) {
    throw new BenchmarkDefinitionError(`exactly 5 frozen cases required, found ${BENCHMARK_CASE_DEFINITIONS.length}`);
  }
  const slots = new Set(BENCHMARK_CASE_DEFINITIONS.map((c) => c.slot));
  const ids = new Set(BENCHMARK_CASE_DEFINITIONS.map((c) => c.caseId));
  if (slots.size !== 5) throw new BenchmarkDefinitionError("benchmark slots must be unique 1-5");
  if (ids.size !== 5) throw new BenchmarkDefinitionError("benchmark case ids must be unique");
  for (const c of BENCHMARK_CASE_DEFINITIONS) {
    if (!FROZEN_SCREENSHOTS[c.caseId]) throw new BenchmarkDefinitionError(`missing frozen screenshot bytes for ${c.caseId}`);
    if (c.definitionVersion !== BENCHMARK_DEFINITION_VERSION) throw new BenchmarkDefinitionError(`case ${c.caseId} definition version mismatch`);
  }
}

export class BenchmarkDefinitionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "BenchmarkDefinitionError";
  }
}
