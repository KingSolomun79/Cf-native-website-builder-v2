import { defineWorkersConfig, readD1Migrations } from "@cloudflare/vitest-pool-workers/config";
import { resolve } from "node:path";
import { writeFileSync, readdirSync, readFileSync, mkdirSync, existsSync } from "node:fs";

// Read all D1 migrations once (in Node) and emit a generated module the
// persistence test imports. The worker isolate cannot reliably read the repo
// filesystem and vite `define` does not transport large strings cleanly, so a
// generated TS module is the robust transport. File boundaries and created
// object names are preserved so setup-migrations.ts can apply only migrations
// missing from persisted storage (including storage written by the older
// all-or-nothing setup, which kept no per-file record).
const migrations = await readD1Migrations(resolve(process.cwd(), "migrations"));
const migrationFiles = migrations.map((m) => {
  const source = m.queries.join("\n");
  const objects = [
    ...source.matchAll(/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)/gi),
    ...source.matchAll(/CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)/gi),
    ...source.matchAll(/CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)/gi),
  ].map((match) => match[1]);
  return {
    name: m.name,
    objects,
    queries: m.queries.map((q) => q.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")),
  };
});
writeFileSync(
  resolve(process.cwd(), "tests", "_generated-migrations.ts"),
  `// AUTO-GENERATED by vitest.config.ts — do not edit.\nexport interface MigrationFile { name: string; objects: string[]; queries: string[] }\nexport const MIGRATION_FILES: MigrationFile[] = [\n${migrationFiles
    .map((m) => `  { name: ${JSON.stringify(m.name)}, objects: ${JSON.stringify(m.objects)}, queries: [\n${m.queries.map((q) => "    `" + q + "`,").join("\n")}\n  ] },`)
    .join("\n")}\n];\n`
);

// Transport the machine-readable capability envelope so runtime tests can
// assert that human- and machine-readable envelopes agree with behavior.
{
  const envelope = readFileSync(resolve(process.cwd(), "v2-docs", "capability-envelope.json"), "utf8");
  writeFileSync(
    resolve(process.cwd(), "src", "domain", "generated", "capability-envelope.ts"),
    `// AUTO-GENERATED from v2-docs/capability-envelope.json — do not edit.
export const CAPABILITY_ENVELOPE = ${envelope.trim()} as const;
`
  );
}

// Transport the deployment configuration for config-level assertions (issue
// #55): the worker isolate cannot read the repo filesystem, so the parsed
// wrangler.jsonc rides a generated module like the migrations above.
{
  const raw = readFileSync(resolve(process.cwd(), "wrangler.jsonc"), "utf8");
  const parsed = JSON.parse(raw.replace(/^[ \t]*\/\/.*$/gm, ""));
  writeFileSync(
    resolve(process.cwd(), "tests", "_generated-wrangler-config.ts"),
    `// AUTO-GENERATED by vitest.config.ts from wrangler.jsonc — do not edit.
export const WRANGLER_CONFIG = ${JSON.stringify(parsed, null, 2)} as const;
export const WRANGLER_CONFIG_RAW = ${JSON.stringify(raw)} as const;
`
  );
}

// Regenerate the canonical prompt body transport from v2-docs/prompts so the
// composed runtime prompts under test always match the markdown sources
// (same output as scripts/generate-prompt-bodies.mjs, including the
// experiment branch's simple-design bodies under v2-docs/prompts/simple/).
{
  const promptsDir = resolve(process.cwd(), "v2-docs", "prompts");
  const simpleDir = resolve(promptsDir, "simple");
  const files = [
    ...readdirSync(promptsDir)
      .filter((name) => name.endsWith(".md") && name !== "PROMPT-MANIFEST.md")
      .sort(),
    ...(existsSync(simpleDir)
      ? readdirSync(simpleDir)
          .filter((name) => name.endsWith(".md"))
          .sort()
          .map((name) => `simple/${name}`)
      : []),
  ];
  const entries = files
    .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(resolve(promptsDir, name), "utf8"))},`)
    .join("\n");
  mkdirSync(resolve(process.cwd(), "src", "domain", "generated"), { recursive: true });
  writeFileSync(
    resolve(process.cwd(), "src", "domain", "generated", "prompt-bodies.ts"),
    `// AUTO-GENERATED from v2-docs/prompts/*.md — do not edit.\n// Source of truth: v2-docs/prompts/ + v2-docs/prompts/PROMPT-MANIFEST.md.\nexport const PROMPT_BODY_FILES: Record<string, string> = {\n${entries}\n};\n`
  );
}

